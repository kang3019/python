t.reset()

# 실습과제 1번
t.shape("turtle")
# 1. 자동차 몸체 그리기 (빨간색)
t.up()
t.goto(-200, -100)
t.down()
t.fillcolor("red")
t.begin_fill()
t.forward(400)
t.left(90)
t.forward(200)
t.left(90)
t.forward(400)
t.left(90)
t.forward(200)
t.end_fill()
# 2. 자동차 상단 그리기 (노란색)
t.up()
