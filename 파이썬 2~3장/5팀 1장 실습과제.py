import turtle as t
import time

# 4번 문제
t.shape("turtle")
t.forward(100)
t.left(90)
t.forward(100)
t.right(90)
t.forward(100)
t.right(90)
t.forward(100)
t.left(90)
t.forward(100)

time.sleep(5)  # 5초 동안 그림 유지
t.reset()

