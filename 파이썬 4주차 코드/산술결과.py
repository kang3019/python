#사용자에게 두개의 정수를 입력받아 변수로 저장
#두 개의 정수의 합,차,곱,나누기,몫,나머지,산술 결과 값을 화면에 출력하기

n1 = int(input('첫 번째 정수 입력 : '));
n2 = int(input('두 번째 정수 입력 : '));

print(n1," + ",n2," = ",n1+n2)
print(n1," - ",n2," = ",n1-n2)
print(n1," / ",n2," = ",n1/n2)
print(n1," * ",n2," = ",n1*n2)
print(n1," // ",n2," = ",n1//n2)#파이썬에만 있는 연산자로 나눗셈 후 정수값만 남음

